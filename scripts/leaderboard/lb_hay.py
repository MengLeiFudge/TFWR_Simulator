def lb_hay():
    clear()
    hay_launch(0, 32)


def hay_launch(lo, hi):
    while hi - lo > 1:
        mid = (lo + hi) // 2
        spawn_drone(hay_launch, mid, hi)
        hi = mid
    if not hay_prepare(lo):
        quick_print("hay_failed", "support", lo)
        clear()
        return
    hay_pair(lo)


def hay_prepare(owner):
    for position in HAY_ROUTES[owner]:
        hay_move(position)
        if not plant(Entities.Bush):
            return False
    return True


def hay_pair(owner):
    first, second = HAY_PAIRS[owner]
    hay_move(first)
    harvest()
    hay_water()
    hay_roll(second)
    move(East)
    harvest()
    hay_water()
    hay_roll(first)
    move(West)
    while True:
        if not can_harvest():
            hay_water()
        harvest()
        if num_items(Items.Hay) >= 2000000000:
            clear()
            return
        hay_roll(second)
        move(East)
        if not can_harvest():
            hay_water()
        harvest()
        if num_items(Items.Hay) >= 2000000000:
            clear()
            return
        hay_roll(first)
        move(West)


def hay_roll(other):
    while True:
        kind, position = get_companion()
        if kind == Entities.Bush and position != other:
            return
        harvest()


def hay_water():
    stock = num_items(Items.Water)
    if stock > 2:
        use_item(Items.Water, 3)
    elif stock > 1:
        use_item(Items.Water, 2)
    elif stock > 0:
        use_item(Items.Water)


def hay_move(position):
    x, y = position
    for target, current, positive, negative in [(x, get_pos_x(), East, West), (y, get_pos_y(), North, South)]:
        count = (target - current) % 32
        direction = positive
        if count > 16:
            count = 32 - count
            direction = negative
        for _ in range(count):
            move(direction)


